// ── Storyboard detection ──────────────────────────────────────────────────────
function detectStoryboard(text: string): boolean {
  return /\|\s*scene\s*\|/i.test(text) || /\|\s*camera\s*\|/i.test(text) || /\|\s*audio\s*\|/i.test(text);
}

// ── Parse markdown table into headers + rows ──────────────────────────────────
function parseMarkdownTable(text: string): { headers: string[]; rows: string[][] } | null {
  const lines = text.split('\n');
  const tableLines = lines.filter(l => l.trim().startsWith('|'));
  if (tableLines.length < 2) return null;
  const headers = tableLines[0].split('|').map(h => h.trim()).filter(Boolean);
  const rows: string[][] = [];
  for (let i = 2; i < tableLines.length; i++) {
    const cells = tableLines[i].split('|').map(c => c.trim()).filter(Boolean);
    if (cells.length > 0) rows.push(cells);
  }
  if (!headers.length || !rows.length) return null;
  return { headers, rows };
}

// ── Extract table text from content ──────────────────────────────────────────
function extractTableText(content: any, textContent: string): string {
  if (typeof content === 'object' && content?.script) {
    return content.script + '\n' + (content.postingTip || '');
  }
  return textContent;
}

// ── jsPDF storyboard export ───────────────────────────────────────────────────
async function exportStoryboardPDF(text: string, username: string) {
  const table = parseMarkdownTable(text);
  if (!table) return false;
  const { jsPDF } = await import('jspdf');
  const { headers, rows } = table;

  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
  const pw = doc.internal.pageSize.getWidth();

  doc.setFillColor(255, 229, 0);
  doc.rect(0, 0, pw, 18, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(28, 28, 30);
  doc.text('ViralForge AI — Content Storyboard', 14, 11.5);
  doc.setFontSize(8);
  doc.setTextColor(80, 80, 80);
  const now = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' });
  doc.text(`@${username}  ·  ${now}`, pw - 14, 11.5, { align: 'right' });

  const colW = (pw - 28) / headers.length;
  let y = 26;

  doc.setFillColor(42, 42, 42);
  doc.rect(14, y - 6, pw - 28, 10, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(255, 229, 0);
  headers.forEach((h, i) => { doc.text(h.toUpperCase(), 14 + colW * i + 2, y); });
  y += 8;

  const LINE_H = 8;
  rows.forEach((row, ri) => {
    const isEven = ri % 2 === 0;
    doc.setFillColor(isEven ? 30 : 38, isEven ? 30 : 38, isEven ? 32 : 40);
    doc.rect(14, y - 5, pw - 28, LINE_H, 'F');
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(220, 220, 220);
    row.forEach((cell, ci) => {
      const truncated = cell.length > 60 ? cell.substring(0, 57) + '...' : cell;
      doc.text(truncated, 14 + colW * ci + 2, y + 1);
    });
    y += LINE_H;
    if (y > doc.internal.pageSize.getHeight() - 20) { doc.addPage(); y = 20; }
  });

  const ph = doc.internal.pageSize.getHeight();
  doc.setFontSize(7);
  doc.setTextColor(100, 100, 100);
  doc.text('Generated by ViralForge AI — viralforge.ai', 14, ph - 6);
  doc.save(`viralforge-storyboard-${Date.now()}.pdf`);
  return true;
}

// ── Platform copy formatters ──────────────────────────────────────────────────
function formatForPlatform(content: any, platform: 'tiktok' | 'reels' | 'shorts'): string {
  const hook = content.hook || '';
  const script = content.script || '';
  const caption = content.caption || '';
  switch (platform) {
    case 'tiktok': {
      const shortCaption = caption.length > 150 ? caption.substring(0, 147) + '...' : caption;
      const topTags = (content.hashtags || []).slice(0, 8).map((t: string) => `#${t}`).join(' ');
      return `${hook}\n\n${shortCaption}\n\n${topTags}`;
    }
    case 'reels': {
      const emojiCaption = caption.replace(/\. /g, ' ✨ ').replace(/! /g, '! 🔥 ');
      const hashtags = (content.hashtags || []).map((t: string) => `#${t}`).join(' ');
      return `${hook} 🎯\n\n${emojiCaption} 💯\n\n${hashtags}`;
    }
    case 'shorts': {
      const scriptSnip = script.length > 200 ? script.substring(0, 197) + '...' : script;
      return `${hook}\n\n${scriptSnip}`;
    }
  }
}

// ── Storyboard Table Component ────────────────────────────────────────────────
function StoryboardTable({ text }: { text: string }) {
  const table = parseMarkdownTable(text);
  if (!table) return null;
  const { headers, rows } = table;
  return (
    <div className="overflow-x-auto rounded-xl border border-primary/20 bg-card/60">
      <table className="w-full text-xs min-w-[500px]">
        <thead>
          <tr className="bg-primary/10 border-b border-primary/20">
            {headers.map((h, i) => (
              <th key={i} className="px-3 py-2.5 text-left font-black text-primary uppercase tracking-wide text-[10px] whitespace-nowrap">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((row, ri) => (
            <tr key={ri} className={`border-b border-border/20 ${ri % 2 === 0 ? 'bg-background/30' : 'bg-card/30'}`}>
              {headers.map((_, ci) => (
                <td key={ci} className="px-3 py-2.5 text-muted-foreground leading-relaxed">
                  {row[ci] || '—'}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

